import type { LucideIcon } from "lucide-react";
import {
  ArrowRight,
  BookOpen,
  ChartNoAxesColumnIncreasing,
  Check,
  ChevronDown,
  ChevronLeft,
  ChevronRight,
  ChevronUp,
  CircleHelp,
  Ellipsis,
  Flag,
  Minus,
  House,
  Layers,
  List,
  MessageSquareText,
  PencilLine,
  Plus,
  Search,
  ShieldCheck,
  Target,
  ThumbsUp,
  Timer,
  X,
} from "lucide-react";
const icons: Record<string, LucideIcon> = {
  minus: Minus,
  home: House,
  chat: MessageSquareText,
  pencil: PencilLine,
  timer: Timer,
  chart: ChartNoAxesColumnIncreasing,
  book: BookOpen,
  flag: Flag,
  arrow: ArrowRight,
  close: X,
  right: ChevronRight,
  left: ChevronLeft,
  check: Check,
  search: Search,
  plus: Plus,
  cards: Layers,
  more: Ellipsis,
  list: List,
  thumb: ThumbsUp,
  shield: ShieldCheck,
  down: ChevronDown,
  up: ChevronUp,
  target: Target,
};
export function Icon({ name, size = 22 }: { name: string; size?: number }) {
  const Component = icons[name] ?? CircleHelp;
  return <Component size={size} strokeWidth={1.7} aria-hidden="true" />;
}
